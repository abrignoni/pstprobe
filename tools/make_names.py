"""Write pstprobe_names.py from the text of [MS-OXPROPS].

    pdftotext -layout "[MS-OXPROPS].pdf" ms-oxprops.txt
    python3 tools/make_names.py ms-oxprops.txt > pstprobe_names.py

Takes each entry's canonical name with its Property ID (PidTag names) or its property set
and LID (PidLid names). Nothing else from the document is kept.
"""
import re
import sys


def main(path):
    text = open(path, encoding="utf-8").read()
    version = re.search(r"\[MS-OXPROPS\] - (v\d{8})", text).group(1)
    tags, lids = {}, {}
    for m in re.finditer(r"Canonical name:\s*(Pid\w+)(.*?)(?=Canonical name:|\Z)", text, re.S):
        name, body = m.group(1), m.group(2)[:1500]
        pid = re.search(r"Property ID:\s*(0x[0-9A-Fa-f]{4})", body)
        if name.startswith("PidTag") and pid:
            tags.setdefault(int(pid.group(1), 16), set()).add(name)
        if name.startswith("PidLid"):
            ps = re.search(r"Property set:\s*\w+\s*\{([0-9A-Fa-f-]{36})\}", body)
            lid = re.search(r"Property long ID \(LID\):\s*(0x[0-9A-Fa-f]{8})", body)
            if ps and lid:
                lids[(ps.group(1).lower(), int(lid.group(1), 16))] = name
    w = sys.stdout.write
    w('"""Canonical property names from Microsoft [MS-OXPROPS] %s.\n\n' % version)
    w("Generated by tools/make_names.py; do not edit. TAGS maps a property ID to its PidTag\n")
    w("name(s); LIDS maps (property set GUID, LID) to its PidLid name.\n\"\"\"\n\n")
    w("SOURCE = \"[MS-OXPROPS] %s\"\n\nTAGS = {\n" % version)
    for k in sorted(tags):
        w("    0x%04X: %r,\n" % (k, tuple(sorted(tags[k]))))
    w("}\n\nLIDS = {\n")
    for (g, lid) in sorted(lids):
        w("    (%r, 0x%08X): %r,\n" % (g, lid, lids[(g, lid)]))
    w("}\n")


if __name__ == "__main__":
    main(sys.argv[1])
